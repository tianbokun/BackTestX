# ── 构建查找表 ──
_SENTIMENT_WORDS: dict[str, float] = {}
for word, w in (
    _POSITIVE_STRONG + _POSITIVE_MODERATE + _POSITIVE_MILD +
    _NEGATIVE_STRONG + _NEGATIVE_MODERATE + _NEGATIVE_MILD
):
    _SENTIMENT_WORDS[word] = w

# 预编译分词器
jieba.initialize()


def analyze_text(text: str) -> dict:
    """分析单条文本的情感.

    Returns:
        sentiment: "positive"/"negative"/"neutral"
        score: -1.0 ~ 1.0
        confidence: 0.0 ~ 1.0 (基于命中的情感词数量)
    """
    if not text or not isinstance(text, str):
        return {"sentiment": "neutral", "score": 0.0, "confidence": 0.0}

    text = text.strip()
    words = list(jieba.cut(text))

    total_score = 0.0
    hit_count = 0

    for i, w in enumerate(words):
        weight = _SENTIMENT_WORDS.get(w)
        if weight is None:
            continue

        modifier = 1.0

        # 检查前 3 个词是否有否定词 (最多跳过一个停用词)
        negated = False
        for j in range(max(0, i - 4), i):
            if words[j] in _NEGATION:
                negated = True
                break

        # 检查前 1~2 个词是否有程度副词
        for j in range(max(0, i - 2), i):
            if words[j] in _AMPLIFIER:
                modifier = _AMPLIFIER[words[j]]
                break

        score = weight * modifier
        if negated:
            score = -score * 0.5

        total_score += score
        hit_count += 1

    if hit_count == 0:
        return {"sentiment": "neutral", "score": 0.0, "confidence": 0.0}

    avg = total_score / hit_count
    avg = max(-1.0, min(1.0, avg))

    sentiment = "positive" if avg > 0.05 else "negative" if avg < -0.05 else "neutral"
    confidence = min(1.0, hit_count / 5.0)

    return {"sentiment": sentiment, "score": round(avg, 4), "confidence": round(confidence, 4)}


def analyze_batch(texts: list[str]) -> list[dict]:
    """批量分析."""
    return [analyze_text(t) for t in texts]


def score_batch(texts: list[str]) -> list[float]:
    """批量分析, 仅返回 score."""
    return [r["score"] for r in analyze_batch(texts)]
